def vc():
    s=input("Enter a string:")

    q=s.count('a')
    b=s.count('A')
    c=s.count('e')
    d=s.count('E')
    e=s.count('i')
    f=s.count('I')
    g=s.count('o')
    h=s.count('O')
    i=s.count('u')
    j=s.count('U')
    p=q+b+c+d+e+f+g+h+i+j

    print("total vowel present in a string is:",p)

vc()
    
